// Joins the 6 migration files into ONE file you can paste into the Supabase SQL Editor.
// Run:  npm run db:bundle      Output: supabase/all_in_one.sql
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const dir = path.join(import.meta.dirname, '..', 'supabase', 'migrations')
const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort()

const header = `-- AUTO-GENERATED by "npm run db:bundle". Do not edit by hand.\n-- Source of truth: supabase/migrations/*.sql (${files.length} files)\n\n`
const body = files.map((f) => `-- ---------- ${f} ----------\n${readFileSync(path.join(dir, f), 'utf8')}`).join('\n')

writeFileSync(path.join(dir, '..', 'all_in_one.sql'), header + body)
console.log(`Bundled ${files.length} migrations -> supabase/all_in_one.sql`)
